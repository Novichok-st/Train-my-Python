# ============================================================
# 6. МНОЖЕСТВА (set)
# ============================================================

s = {1, 2, 3, 4}
other = {3, 4, 5, 6}

# --- Добавление ---
s.add(5)                   # Добавляет один элемент
s.update([6, 7, 8])        # Добавляет элементы из объекта

# --- Удаление ---
s.remove(2)                # Удаляет элемент; ошибка, если его нет
s.discard(100)             # Удаляет, если элемент существует
s.pop()                    # Удаляет и возвращает произвольный элемент
s.clear()                  # Очищает множество

# --- Объединение ---
s | other                  # Все элементы обоих множеств
s.union(other)              # То же самое

# --- Пересечение ---
s & other                  # Только общие элементы
s.intersection(other)       # То же самое

# --- Разность ---
s - other                  # Элементы s, которых нет в other
s.difference(other)         # То же самое

# --- Симметрическая разность ---
s ^ other                  # Элементы, которые есть только в одном множестве
s.symmetric_difference(other)

# --- Проверки ---
3 in s                     # Есть ли элемент?
len(s)                     # Количество уникальных элементов
s.isdisjoint(other)        # Нет ли общих элементов?
s.issubset(other)          # s является подмножеством other?
s.issuperset(other)        # s содержит все элементы other?

# --- Изменение самого множества ---
s.intersection_update(other)       # Оставляет только общие элементы
s.difference_update(other)         # Удаляет элементы из other
s.symmetric_difference_update(other)  # Оставляет элементы только из одного
s.update(other)                    # Добавляет элементы other
s |= other                         # Объединение с изменением s
s &= other                         # Пересечение с изменением s
s -= other                         # Разность с изменением s
s ^= other                         # Симметрическая разность с изменением s

# --- Преобразование ---
set([1, 1, 2, 2, 3])      # {1, 2, 3}
set("banana")              # Уникальные символы строки
set()                      # Пустое множество

# ВАЖНО:
# Множество хранит только уникальные элементы.
# Порядок элементов не гарантируется.
# Индексов нет: s[0] вызовет ошибку.
# Элементы должны быть хешируемыми.


