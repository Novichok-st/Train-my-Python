# ============================================================
# 1. СТРОКИ (str)
# ============================================================

a = "Pythonomania"

# --- Поиск и подсчёт ---
a.count("o")              # Количество символов "o"
a.find("o")               # Индекс первого "o", -1 если не найден
a.rfind("o")              # Индекс последнего "o"
a.index("o")              # Индекс первого "o", ошибка если не найден
a.rindex("o")             # Индекс последнего "o", ошибка если не найден

# --- Проверка содержимого ---
a.startswith("Py")        # Начинается ли строка с "Py" -> True
a.endswith("nia")         # Заканчивается ли на "nia" -> True
a.isalpha()               # Только буквы?
a.isdigit()               # Только цифры?
a.isdecimal()             # Только десятичные цифры?
a.isnumeric()             # Только числовые символы?
a.isalnum()               # Только буквы и цифры?
a.islower()               # Все буквенные символы в нижнем регистре?
a.isupper()               # Все буквенные символы в верхнем регистре?
a.istitle()               # Каждое слово начинается с заглавной?
a.isspace()               # Только пробельные символы?
a.isascii()               # Только символы ASCII?
a.isprintable()           # Все символы печатные?

# --- Изменение регистра ---
a.lower()                 # Все буквы в нижний регистр
a.upper()                 # Все буквы в верхний регистр
a.capitalize()            # Первая буква заглавная, остальные строчные
a.title()                 # Первые буквы слов заглавные
a.swapcase()              # Меняет регистр на противоположный
a.casefold()              # Для сравнения строк без учёта регистра

# --- Удаление пробелов и символов по краям ---
a.strip()                 # Убирает пробелы по краям
a.lstrip()                # Убирает пробелы слева
a.rstrip()                # Убирает пробелы справа
a.strip("Pia")            # Убирает указанные символы по краям

# --- Замена ---
a.replace("o", "0")       # Заменяет все "o" на "0"
a.replace("o", "0", 1)    # Заменяет только первое совпадение

# --- Разделение строки ---
a.split("o")              # Разбивает строку по разделителю
a.rsplit("o", 1)          # Разбивает справа, максимум 1 раз
a.partition("o")          # Делит на 3 части по первому совпадению
a.rpartition("o")         # Делит на 3 части по последнему совпадению
a.splitlines()            # Разбивает по границам строк

# --- Объединение ---
"-".join(["Python", "Java"])  # "Python-Java"

# --- Выравнивание ---
a.center(20)              # Выравнивает по центру
a.ljust(20)               # Выравнивает влево
a.rjust(20)               # Выравнивает вправо
"7".zfill(4)              # "0007"

# --- Дополнительные операции ---
a.removeprefix("Py")      # Убирает указанный префикс в начале
a.removesuffix("nia")     # Убирает указанный суффикс в конце
a.expandtabs(4)           # Заменяет табуляцию пробелами

# --- Форматирование ---
name = "Alex"
age = 15

f"Имя: {name}, возраст: {age}"  # Вставляет значения в строку
"{} + {}".format(2, 3)           # Форматирует строку
"{:04d}".format(7)               # "0007"

# --- Операции со строками ---
a[0]                      # Первый символ -> "P"
a[-1]                     # Последний символ -> "a"
a[0:4]                    # Срез -> "Pyth"
a[::-1]                   # Строка в обратном порядке
"Py" in a                 # Проверяет наличие подстроки
a + "!"                   # Объединяет строки
a * 3                     # Повторяет строку 3 раза
len(a)                    # Длина строки

