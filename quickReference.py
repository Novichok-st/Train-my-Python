class Number:
    def __init__(self, value):
        self.value = value

    def __str__(self):
        return str(self.value)  # Для str(obj) и print(obj)

    def __repr__(self):
        return f"Number({self.value})"  # Представление объекта

    def __len__(self):
        return 1               # Для len(obj)

    def __bool__(self):
        return self.value != 0  # Для bool(obj)

    def __add__(self, other):
        return Number(self.value + other.value)  # obj1 + obj2

    def __eq__(self, other):
        return self.value == other.value  # obj1 == obj2

    def __lt__(self, other):
        return self.value < other.value   # obj1 < obj2


