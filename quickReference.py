# ============================================================
# 4. СЛОВАРИ (dict)
# ============================================================

d = {"name": "Alex", "age": 15}

# --- Получение значений ---
d["name"]                  # Значение по ключу; ошибка, если ключа нет
d.get("name")              # Значение по ключу
d.get("city", "Unknown")   # Значение или запасной вариант

# --- Получение ключей и значений ---
d.keys()                   # Все ключи
d.values()                 # Все значения
d.items()                  # Пары (ключ, значение)

# --- Добавление и изменение ---
d["age"] = 16              # Меняет значение существующего ключа
d["city"] = "Almaty"       # Добавляет новую пару
d.update({"age": 17})      # Обновляет значения
d.setdefault("level", 1)   # Создаёт ключ, если его нет

# --- Удаление ---
d.pop("age")               # Удаляет ключ и возвращает его значение
d.pop("unknown", None)     # Безопасное удаление отсутствующего ключа
d.popitem()                # Удаляет последнюю добавленную пару
del d["name"]              # Удаляет пару по ключу
d.clear()                  # Удаляет все пары

# --- Проверка и копирование ---
"name" in d                # Проверяет наличие ключа
len(d)                     # Количество пар
d.copy()                   # Поверхностная копия словаря
dict(name="Alex", age=15)  # Создание словаря

# --- Перебор ---
for key in d:
    print(key)             # Перебирает ключи

for value in d.values():
    print(value)           # Перебирает значения

for key, value in d.items():
    print(key, value)      # Перебирает пары

# --- Генераторы словарей ---
{i: i * 2 for i in range(5)}
# {0: 0, 1: 2, 2: 4, 3: 6, 4: 8}

{letter: "буква" for letter in "abc"}
# {"a": "буква", "b": "буква", "c": "буква"}

# --- Объединение словарей ---
{"a": 1} | {"b": 2}        # Новый словарь {"a": 1, "b": 2}
d |= {"level": 2}          # Обновляет d

# ВАЖНО:
# Ключи должны быть хешируемыми.
# Обычно используют строки, числа и кортежи из хешируемых объектов.
# d[key] обращается к значению по ключу.
# Чтобы изменить значение: d[key] = новое_значение.
# Одинаковые ключи не могут существовать в словаре дважды.


